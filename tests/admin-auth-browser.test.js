import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync,readFileSync,mkdirSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {createServer} from 'node:http';
import {Store} from '../server/store.js';
import {createApp} from '../server/app.js';
import {chromium} from '../server/browser-runtime.js';

test('administrator setup, logout, login, password change and expired sessions protect the UI; help is removed',{timeout:60000},async t=>{
  const dir=mkdtempSync(join(tmpdir(),'admin-auth-ui-')),store=new Store(dir);
  const server=createServer().listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  const origin=`http://127.0.0.1:${server.address().port}`,services=createApp(store,{allowedHosts:[new URL(origin).host]});server.on('request',services.app);
  let browser;t.after(async()=>{await browser?.close();await Promise.all([services.checker.cancel(),services.pat.stop(),services.workbuddy.stop()]);await services.integrations.stop();server.closeAllConnections();await new Promise(r=>server.close(r));store.close();rmSync(dir,{recursive:true,force:true});});
  browser=await chromium.launch({headless:true,executablePath:chromium.executablePath()});
  const page=await browser.newPage({viewport:{width:1280,height:850}}),errors=[];page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(10000);
  await page.goto(origin);await page.getByRole('heading',{name:'设置管理员',exact:true}).waitFor();
  assert.equal(await page.getByRole('table',{name:'账号列表'}).count(),0);
  const output=resolve('output/playwright/admin-auth');mkdirSync(output,{recursive:true});
  await page.screenshot({path:join(output,'setup.png'),fullPage:true,animations:'disabled'});
  await page.getByLabel('一次性设置码',{exact:true}).fill(readFileSync(join(dir,'admin-setup-code.txt'),'utf8').trim());
  await page.getByLabel('管理员账号',{exact:true}).fill('admin');
  await page.getByLabel('密码',{exact:true}).fill('browser-password-123');await page.getByLabel('确认密码',{exact:true}).fill('browser-password-123');
  await page.getByRole('button',{name:'设置并登录',exact:true}).click();await page.getByRole('button',{name:'退出登录',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:/^(说明|使用说明)$/}).count(),0);
  await page.getByRole('button',{name:/安全中心/}).click();
  await page.getByRole('button',{name:'修改登录密码',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'修改登录密码',exact:true});
  await dialog.getByLabel('当前密码',{exact:true}).fill('browser-password-123');await dialog.getByLabel('新密码',{exact:true}).fill('browser-password-new');await dialog.getByLabel('确认新密码',{exact:true}).fill('browser-password-new');
  await dialog.getByRole('button',{name:'保存密码',exact:true}).click();await dialog.waitFor({state:'hidden'});
  await page.getByRole('button',{name:'退出登录',exact:true}).click();await page.getByRole('heading',{name:'登录工作台',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'新增账号',exact:true}).count(),0);
  await page.screenshot({path:join(output,'login.png'),fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:join(output,'mobile-login.png'),fullPage:true,animations:'disabled'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.getByLabel('管理员账号',{exact:true}).fill('admin');await page.getByLabel('密码',{exact:true}).fill('browser-password-123');await page.getByRole('button',{name:'登录',exact:true}).click();await page.getByRole('alert').filter({hasText:'账号或密码不正确'}).waitFor();
  await page.getByLabel('密码',{exact:true}).fill('browser-password-new');await page.getByRole('button',{name:'登录',exact:true}).click();await page.getByRole('button',{name:'退出登录',exact:true}).waitFor();
  assert.ok(!(await page.evaluate(()=>JSON.stringify({...localStorage,...sessionStorage}))).includes('browser-password'));
  store.db.exec('DELETE FROM admin_sessions');
  await page.getByRole('button',{name:'API 管理',exact:true}).click();await page.getByRole('heading',{name:'登录工作台',exact:true}).waitFor();
  assert.deepEqual(errors,[]);
});
