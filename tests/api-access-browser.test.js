import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync,rmSync,mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join,resolve } from 'node:path';
import { createServer } from 'node:http';
import { Store } from '../server/store.js';
import { createApp } from './authenticated-app.js';
import { chromium } from '../server/browser-runtime.js';

test('API management creates a one-time secret, edits permissions, disables and deletes keys on desktop and mobile',{timeout:60000},async t=>{
  const dir=mkdtempSync(join(tmpdir(),'api-management-ui-')),store=new Store(dir);
  const server=createServer().listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  const origin=`http://127.0.0.1:${server.address().port}`;
  const services=createApp(store,{allowedHosts:[new URL(origin).host],apiOrigin:'https://api.example.test'});server.on('request',services.app);
  const group=store.organization.save('groups',{name:'注册工具来源'}),tag=store.organization.save('tags',{name:'项目 A',color:'teal'});
  let browser;t.after(async()=>{await browser?.close();await Promise.all([services.checker.cancel(),services.pat.stop(),services.workbuddy.stop()]);await services.integrations.stop();server.closeAllConnections();await new Promise(r=>server.close(r));store.close();rmSync(dir,{recursive:true,force:true});});
  browser=await chromium.launch({headless:true,executablePath:chromium.executablePath()});
  const page=await browser.newPage({viewport:{width:1280,height:850}}),errors=[];page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(5000);
  await page.goto(origin);await page.getByRole('button',{name:'API 管理',exact:true}).click();
  await page.getByRole('button',{name:'创建密钥',exact:true}).click();
  let dialog=page.getByRole('dialog',{name:'创建 API 密钥',exact:true});
  await dialog.getByLabel('密钥名称').fill('注册工具');
  await dialog.getByLabel('有效期').selectOption('30');
  await dialog.getByLabel('来源分组').selectOption(group.id);
  await dialog.getByRole('checkbox',{name:'项目 A',exact:true}).check();
  await dialog.getByRole('button',{name:'创建密钥',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'保存 API 密钥',exact:true});
  await dialog.waitFor();const secret=await dialog.getByLabel('完整密钥').inputValue();assert.match(secret,/^adk_/);
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:()=>Promise.reject(new Error('blocked'))}}));
  await dialog.getByRole('button',{name:'复制密钥',exact:true}).click();
  await dialog.getByRole('alert').filter({hasText:'复制失败'}).waitFor();
  await dialog.getByRole('button',{name:'完成',exact:true}).click();
  const row=page.getByRole('row').filter({hasText:'注册工具'});await row.waitFor();
  assert.equal(services.access.list()[0].groupId,group.id);assert.deepEqual(services.access.list()[0].tagIds,[tag.id]);
  const imported=services.access.import(services.access.list()[0].id,{accounts:[{email:'bound@example.test',username:'bound',password:'fixture-password'}]});
  assert.equal(store.get(imported.results[0].id).groupId,group.id);assert.deepEqual(store.get(imported.results[0].id).tagIds,[tag.id]);
  assert.ok(!(await page.locator('body').innerText()).includes(secret));
  await row.getByRole('button',{name:'编辑 注册工具',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'编辑 API 密钥',exact:true});
  const output=resolve('output/playwright/api-access');mkdirSync(output,{recursive:true});
  await dialog.waitFor();
  await page.screenshot({path:join(output,'key-editor.png'),fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:join(output,'key-editor-mobile.png'),fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:1280,height:850});
  await dialog.getByLabel('来源分组').selectOption('');
  await dialog.getByRole('checkbox',{name:'项目 A',exact:true}).uncheck();
  await dialog.getByLabel('导入账号',{exact:true}).uncheck();await dialog.getByRole('button',{name:'保存修改',exact:true}).click();
  await dialog.waitFor({state:'hidden'});assert.deepEqual(services.access.list()[0].scopes,['organization:read']);
  assert.equal(services.access.list()[0].groupId,null);assert.deepEqual(services.access.list()[0].tagIds,[]);
  assert.equal(store.get(imported.results[0].id).groupId,group.id);
  await row.getByRole('button',{name:'停用',exact:true}).click();await row.getByText('已停用',{exact:true}).waitFor();
  assert.equal(services.access.list()[0].enabled,false);
  await page.getByText('调用文档',{exact:true}).click();await page.getByRole('button',{name:'复制请求示例'}).waitFor();
  await page.screenshot({path:join(output,'desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:join(output,'mobile.png'),fullPage:true});
  await row.getByRole('button',{name:'删除 注册工具',exact:true}).click();
  dialog=page.getByRole('alertdialog');await dialog.getByRole('button',{name:'删除密钥',exact:true}).click();
  await page.getByText('还没有 API 密钥',{exact:true}).waitFor();assert.equal(services.access.list().length,0);assert.deepEqual(errors,[]);
});
