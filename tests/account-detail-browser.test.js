import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createServer } from 'node:http';
import express from 'express';
import { Store } from '../server/store.js';
import { createApp } from './authenticated-app.js';
import { chromium } from '../server/browser-runtime.js';

test('account details keep common actions in view and preserve safe credential, edit and selection interactions', {timeout:120000}, async t => {
  const directory=mkdtempSync(join(tmpdir(),'account-detail-ui-'));
  const store=new Store(directory);
  const group=store.organization.save('groups',{name:'自注册'});
  const tag=store.organization.save('tags',{name:'项目 Alpha',color:'teal'});
  const account=store.create({username:'detail-fixture',email:'detail@example.test',password:'synthetic-password',totp:'JBSWY3DPEHPK3PXP',groupId:group.id,tagIds:[tag.id],notes:'用于测试凭据和验证码的查看与复制。'});
  store.create({username:'empty-fixture',email:'empty@example.test',password:'synthetic-password',notes:''});
  store.setCheck(account.id,account.username,{status:'reachable',message:'GitHub 公开资料可访问；此结果不能判断登录限制或风控状态'});
  const server=createServer().listen(0,'127.0.0.1');
  await new Promise(r=>server.once('listening',r));
  const origin=`http://127.0.0.1:${server.address().port}`;
  const services=createApp(store,{allowedHosts:[new URL(origin).host],fetcher:async()=>{throw new Error('External requests prohibited in fixture');}});
  const fixture=express();
  if(process.env.ACCOUNT_DETAIL_BUILD)fixture.use(express.static(resolve(process.env.ACCOUNT_DETAIL_BUILD)));
  fixture.use(services.app);server.on('request',fixture);
  let browser;
  t.after(async()=>{await browser?.close();services.schedule?.stop();await Promise.all([services.checker.cancel(),services.pat.stop(),services.workbuddy.stop()]);await services.integrations.stop();server.closeAllConnections();await new Promise(r=>server.close(r));store.close();rmSync(directory,{recursive:true,force:true});});
  browser=await chromium.launch({headless:true,executablePath:chromium.executablePath()});
  const page=await browser.newPage({viewport:{width:1280,height:800}});
  page.setDefaultTimeout(10000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const shots=resolve('output/playwright/account-detail');mkdirSync(shots,{recursive:true});
  await page.goto(origin);
  const row=page.getByRole('row').filter({has:page.getByRole('button',{name:'detail-fixture',exact:true})});
  await row.getByRole('button',{name:'detail-fixture',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'账号详情',exact:true});
  const body=dialog.locator('.modal-body');
  await dialog.getByRole('button',{name:'获取验证码',exact:true}).waitFor();
  await page.screenshot({path:join(shots,'desktop.png'),animations:'disabled'});
  assert.equal(await body.evaluate(el=>el.scrollHeight<=el.clientHeight+1),true,'ordinary details fit at 1280×800 without hiding ownership and selection below a scroll');
  assert.equal(await dialog.getByText('公开可访问',{exact:true}).count(),1);
  assert.equal(await dialog.getByText('未分配',{exact:true}).count(),1);
  assert.equal(await dialog.getByRole('button',{name:'选用此账号',exact:true}).isDisabled(),false);
  await dialog.getByLabel('邮箱',{exact:true}).click();
  assert.equal(await dialog.getByLabel('邮箱',{exact:true}).locator('..').evaluate(el=>getComputedStyle(el).boxShadow),'none','pointer focus does not add the old blue input glow');

  await page.route(`**/api/accounts/${account.id}/secrets`,route=>route.fulfill({json:{password:'synthetic-visible-password',totp:'JBSWY3DPEHPK3PXP',otp:{code:'123456',expiresAt:Date.now()+3000}}}));
  await page.evaluate(()=>{window.testClipboard=[];Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async value=>window.testClipboard.push(value)}});});
  await dialog.getByRole('button',{name:'复制邮箱',exact:true}).click();
  await dialog.getByText('邮箱已复制',{exact:true}).waitFor();
  assert.deepEqual(await page.evaluate(()=>window.testClipboard),['detail@example.test']);
  await dialog.getByRole('button',{name:'显示密码',exact:true}).click();
  assert.equal(await dialog.getByLabel('密码',{exact:true}).inputValue(),'synthetic-visible-password');
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
  await dialog.getByRole('button',{name:'显示密码',exact:true}).waitFor();
  assert.notEqual(await dialog.getByLabel('密码',{exact:true}).inputValue(),'synthetic-visible-password');
  await page.evaluate(()=>Object.defineProperty(document,'hidden',{configurable:true,value:false}));
  await dialog.getByRole('button',{name:'获取验证码',exact:true}).click();
  await dialog.getByText('123456',{exact:true}).waitFor();
  await dialog.getByRole('button',{name:'复制验证码',exact:true}).click();
  assert.deepEqual(await page.evaluate(()=>window.testClipboard),['detail@example.test','123456']);
  await dialog.getByText('已过期',{exact:true}).waitFor();
  assert.equal(await dialog.getByRole('button',{name:'复制验证码',exact:true}).isDisabled(),true);
  await page.clock.install();
  await dialog.getByRole('button',{name:'显示密码',exact:true}).click();
  assert.equal(await dialog.getByLabel('密码',{exact:true}).inputValue(),'synthetic-visible-password');
  await page.clock.fastForward(30001);
  await dialog.getByRole('button',{name:'显示密码',exact:true}).waitFor();
  assert.notEqual(await dialog.getByLabel('密码',{exact:true}).inputValue(),'synthetic-visible-password','visible credentials automatically hide after 30 seconds');
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw new Error('denied');}}}));
  await dialog.getByRole('button',{name:'复制邮箱',exact:true}).click();
  await dialog.getByRole('alert').filter({hasText:'复制失败'}).waitFor();

  for(const width of [390,320]){
    await page.setViewportSize({width,height:800});
    assert.equal(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,`no dialog overflow at ${width}`);
    assert.equal(await body.evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,`no body overflow at ${width}`);
    await body.evaluate(el=>{el.scrollTop=0;});
    await page.screenshot({path:join(shots,`mobile-${width}-top.png`),animations:'disabled'});
    await dialog.getByRole('button',{name:'选用此账号',exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:join(shots,`mobile-${width}.png`),animations:'disabled'});
    const close=dialog.getByRole('button',{name:'关闭',exact:true}).last();await close.focus();await page.keyboard.press('Tab');
    assert.equal(await dialog.getByRole('button',{name:'关闭',exact:true}).first().evaluate(el=>el===document.activeElement),true,'Tab loops within the dialog');
    assert.notEqual(await dialog.getByRole('button',{name:'关闭',exact:true}).first().evaluate(el=>getComputedStyle(el).outlineStyle),'none','keyboard focus stays visible');
  }
  await page.keyboard.press('Escape');
  await dialog.waitFor({state:'hidden'});
  await page.setViewportSize({width:1280,height:800});
  await row.getByRole('button',{name:'编辑',exact:true}).click();
  const edit=page.getByRole('dialog',{name:'编辑账号',exact:true});
  await edit.getByLabel('邮箱',{exact:true}).fill('changed@example.test');
  await edit.getByRole('button',{name:'修改密码',exact:true}).click();
  await edit.getByLabel('密码',{exact:true}).fill('');
  await edit.getByRole('button',{name:'保存修改',exact:true}).click();
  await edit.getByRole('alert').filter({hasText:'密码不能为空'}).waitFor();
  await edit.getByRole('button',{name:'取消修改密码',exact:true}).click();
  await page.keyboard.press('Escape');
  await page.getByRole('alertdialog').getByRole('button',{name:'继续编辑',exact:true}).click();
  assert.equal(await edit.getByLabel('邮箱',{exact:true}).inputValue(),'changed@example.test');
  await edit.getByRole('button',{name:'保存修改',exact:true}).click();
  await edit.getByText('账号修改已保存',{exact:true}).waitFor();
  assert.equal(store.get(account.id).email,'changed@example.test');
  await page.screenshot({path:join(shots,'edit.png'),animations:'disabled'});
  await page.keyboard.press('Escape');
  await row.getByRole('button',{name:'detail-fixture',exact:true}).click();
  await dialog.getByRole('button',{name:'选用此账号',exact:true}).click();
  const selection=page.getByRole('dialog').filter({has:page.getByRole('button',{name:/确认选用/})});
  await selection.getByRole('button',{name:/确认选用/}).click();
  await dialog.getByRole('button',{name:'释放标记',exact:true}).waitFor();
  await dialog.getByRole('button',{name:'释放标记',exact:true}).click();
  await page.getByRole('alertdialog').getByRole('button',{name:'确认释放',exact:true}).click();
  await dialog.getByRole('button',{name:'选用此账号',exact:true}).waitFor();
  assert.equal(store.get(account.id).selectedAt,null);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'empty-fixture',exact:true}).click();
  assert.equal(await dialog.getByRole('button',{name:'获取验证码',exact:true}).isDisabled(),true);
  assert.equal(await dialog.getByRole('button',{name:'复制TOTP 密钥',exact:true}).isDisabled(),true);
  assert.equal(await dialog.getByRole('button',{name:'选用此账号',exact:true}).isDisabled(),true);
  assert.equal(await body.evaluate(el=>el.scrollHeight<=el.clientHeight+1),true);
  await page.screenshot({path:join(shots,'empty.png'),animations:'disabled'});
  assert.deepEqual(errors,[]);
});
