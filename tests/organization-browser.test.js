import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createServer } from 'node:http';
import { Store } from '../server/store.js';
import { createApp } from './authenticated-app.js';
import { chromium } from '../server/browser-runtime.js';

test('organization workflow persists groups, tags and import choices; filters, bulk editing and mobile layout work', {timeout:120000}, async t=>{
  const directory=mkdtempSync(join(tmpdir(),'organization-browser-'));
  const store=new Store(directory);
  const server=createServer().listen(0,'127.0.0.1');
  await new Promise(r=>server.once('listening',r));
  const base=`http://127.0.0.1:${server.address().port}`;
  const {app,integrations,workbuddy,pat,checker}=createApp(store,{allowedHosts:[new URL(base).host],fetcher:async()=>{throw new Error('No external requests in UI verification');}});
  server.on('request',app);
  let browser;
  t.after(async()=>{await browser?.close();await Promise.all([checker.cancel(),pat.stop(),workbuddy.stop()]);await integrations.stop();await new Promise(r=>server.close(r));store.close();rmSync(directory,{recursive:true,force:true});});
  browser=await chromium.launch({headless:true,executablePath:chromium.executablePath()});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.setDefaultTimeout(12000);
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const group=store.organization.save('groups',{name:'自注册'});
  const tag=store.organization.save('tags',{name:'开发测试',color:'teal'});
  for(let i=1;i<=18;i++) {
    const a=store.create({username:`octo-${String(i).padStart(2,'0')}`,email:`account${i}@example.test`,password:'fixture-password',totp:i%3?'JBSWY3DPEHPK3PXP':'',groupId:i%2?group.id:null,tagIds:i%2?[tag.id]:[]});
    if(i%5)store.setCheck(a.id,a.username,{status:['reachable','reachable','missing','error','limited'][i%5],message:i%5===2?'公开资料不可访问，不能仅据此判定封禁':'合成数据的公开检测结果'});
  }
  await page.goto(base);
  await page.getByRole('button',{name:/分组管理/}).click();
  await page.getByRole('button',{name:'新建分组',exact:true}).first().click();
  await page.getByRole('textbox',{name:'分组名称'}).fill('供应商 A');
  await page.getByRole('button',{name:'保存分组',exact:true}).click();
  await page.getByText('供应商 A',{exact:true}).waitFor();
  await page.getByRole('button',{name:/标签管理/}).click();
  await page.getByRole('button',{name:'新建标签',exact:true}).first().click();
  await page.getByRole('textbox',{name:'标签名称'}).fill('项目 Atlas');
  await page.getByLabel('紫色',{exact:true}).check();
  await page.getByRole('button',{name:'保存标签',exact:true}).click();
  await page.getByText('项目 Atlas',{exact:true}).waitFor();
  await page.getByRole('button',{name:/账号管理/}).click();
  await page.getByRole('button',{name:'批量导入',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByRole('combobox',{name:'来源分组',exact:true}).selectOption({label:'供应商 A'});
  await dialog.getByLabel('项目 Atlas',{exact:true}).check();
  await dialog.getByLabel('账号内容',{exact:true}).fill('imported@example.test----fixture-password----imported-account');
  await dialog.getByRole('button',{name:'预览并校验'}).click();
  await dialog.getByRole('button',{name:'导入 1 个账号'}).click();
  await page.getByRole('button',{name:'imported-account',exact:true}).waitFor();
  let imported=store.list().find(a=>a.username==='imported-account');
  assert.equal(store.organization.list().groups.find(g=>g.id===imported.groupId).name,'供应商 A');
  assert.equal(imported.tagIds.length,1);
  await page.getByRole('combobox',{name:'筛选来源分组'}).selectOption({label:'供应商 A'});
  assert.equal(await page.locator('tbody tr').count(),1);
  await page.getByRole('checkbox',{name:'全选当前页'}).check();
  await page.getByRole('button',{name:'分组 / 标签',exact:true}).click();
  await dialog.getByLabel('开发测试',{exact:true}).check();
  await dialog.getByRole('button',{name:'保存整理'}).click();
  await page.getByText('分组与标签已更新',{exact:true}).waitFor();
  assert.equal(store.get(imported.id).tagIds.length,2);
  await page.getByRole('combobox',{name:'筛选用途标签'}).selectOption({label:'无标签'});
  await page.getByText('没有符合条件的账号',{exact:true}).waitFor();
  assert.equal(await page.getByText(/已勾选 \d+ 个账号/).count(),0);
  await page.getByRole('button',{name:'重置筛选'}).click();
  await page.getByRole('button',{name:/无法判断/}).first().click();
  assert.equal(await page.locator('tbody tr').count(),7);
  await page.getByRole('button',{name:'重置筛选'}).click();
  await page.getByRole('button',{name:'imported-account',exact:true}).click();
  await dialog.getByRole('button',{name:'整理分类'}).click();
  const top=page.getByRole('dialog',{name:'整理分组与标签',exact:true});
  await top.getByLabel('开发测试',{exact:true}).uncheck();
  await top.getByRole('button',{name:'保存整理'}).click();
  await page.getByRole('dialog',{name:'整理分组与标签',exact:true}).waitFor({state:'hidden'});
  assert.equal(store.get(imported.id).tagIds.length,1);
  await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).first().click();
  mkdirSync(resolve('output/playwright/organization'),{recursive:true});
  await page.mouse.move(1000,80);
  await page.screenshot({path:resolve('output/playwright/organization/desktop.png'),animations:'disabled'});
  await page.getByRole('button',{name:/分组管理/}).click();
  await page.getByRole('button',{name:'编辑分组 供应商 A',exact:true}).click();
  await page.getByRole('textbox',{name:'分组名称'}).fill('外部采购');
  await page.getByRole('button',{name:'保存分组',exact:true}).click();
  await page.getByRole('button',{name:'删除分组 外部采购',exact:true}).click();
  await page.getByRole('alertdialog').getByRole('button',{name:'删除分组',exact:true}).click();
  await page.getByRole('alertdialog').waitFor({state:'hidden'});
  assert.equal(store.get(imported.id).groupId,null);
  await page.getByRole('button',{name:/标签管理/}).click();
  await page.getByRole('heading',{name:'标签管理',exact:true}).waitFor();
  await page.mouse.move(1000,80);
  await page.screenshot({path:resolve('output/playwright/organization/tags.png'),animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:/账号管理/}).click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile page must not overflow');
  await page.screenshot({path:resolve('output/playwright/organization/mobile.png'),animations:'disabled'});
  await page.getByRole('button',{name:'批量导入',exact:true}).click();
  await page.getByRole('dialog',{name:'导入 GitHub 账号',exact:true}).waitFor();
  await page.screenshot({path:resolve('output/playwright/organization/mobile-import.png'),animations:'disabled'});
  assert.equal(await page.evaluate(()=>document.querySelector('dialog').getBoundingClientRect().width<=innerWidth),true);
  assert.deepEqual(errors,[]);
});
